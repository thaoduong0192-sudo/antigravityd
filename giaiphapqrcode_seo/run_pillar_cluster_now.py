import os
import sys
import time
import json
from datetime import datetime
from bs4 import BeautifulSoup

sys.stdout.reconfigure(encoding='utf-8')

# Import the existing tool functions
import fully_auto_giaiphapqrcode as auto_tool

def main():
    print("=============================================================")
    print("   GIAIPHAPQRCODE – ĐĂNG BÀI PILLAR & CLUSTER TỨC THÌ")
    print("=============================================================")
    
    pillar_kw = ""
    if len(sys.argv) > 1:
        pillar_kw = " ".join(sys.argv[1:])
    else:
        # Tự động lấy từ khóa tiếp theo chưa xong trong database.json
        db_path = "database.json"
        if os.path.exists(db_path):
            try:
                with open(db_path, "r", encoding="utf-8") as f:
                    db = json.load(f)
                    for k_obj in db.get("keywords", []):
                        if k_obj.get("published_count", 0) < 10:
                            pillar_kw = k_obj.get("keyword", "")
                            break
            except:
                pass
                
        if not pillar_kw:
            print("[-] Không còn từ khóa nào cần đăng trong database.json! Vui lòng nhập keyword qua tham số.")
            return

    print(f"[*] TỪ KHÓA ĐANG XỬ LÝ: {pillar_kw}")

    db_path = "database.json"
    
    # Init or load database
    if os.path.exists(db_path):
        try:
            with open(db_path, "r", encoding="utf-8") as f:
                db = json.load(f)
        except:
            db = {"revenue": 0, "keywords": [], "articles": []}
    else:
        db = {"revenue": 0, "keywords": [], "articles": []}
        
    # Find or add the keyword to database
    kw_index = -1
    for i, k_obj in enumerate(db.get("keywords", [])):
        if k_obj.get("keyword") == pillar_kw:
            kw_index = i
            break
            
    if kw_index == -1:
        kw_obj = {
            "keyword": pillar_kw,
            "published_count": 0,
            "longtails": [],
            "pillar_url": "",
            "history": []
        }
        db["keywords"].append(kw_obj)
        kw_index = len(db["keywords"]) - 1
    
    active_kw_obj = db["keywords"][kw_index]
    published_count = active_kw_obj.get("published_count", 0)
    
    if published_count >= 10:
        print(f"[-] Từ khóa '{pillar_kw}' đã đăng đủ 10 bài! (1 Pillar + 9 Cluster). Bỏ qua.")
        return
        
    # Try loading optional functions
    try:
        from hoiky_seo_api import research_competitors, get_woo_products, auto_discount_product
    except:
        def research_competitors(kw): return ""
        def get_woo_products(): return []
        def auto_discount_product(p): return None
        
    products = get_woo_products()
    
    while active_kw_obj.get("published_count", 0) < 10:
        current_published = active_kw_obj.get("published_count", 0)
        is_pillar = (current_published == 0)
        
        if is_pillar:
            target_keyword = pillar_kw
            print(f"\n[*] Đang xử lý bài PILLAR (1/10) cho từ khóa: '{target_keyword}'")
        else:
            if "longtails" not in active_kw_obj or len(active_kw_obj["longtails"]) < 9:
                print(f"\n[AI] Phân tích và sinh 9 từ khóa vệ tinh (Cluster) cho '{pillar_kw}'...")
                active_kw_obj["longtails"] = auto_tool.generate_longtails_for_pillar(pillar_kw)
                db["keywords"][kw_index]["longtails"] = active_kw_obj["longtails"]
                # Save temporarily
                with open(db_path, "w", encoding="utf-8") as f:
                    json.dump(db, f, ensure_ascii=False, indent=2)
            
            longtail_idx = current_published - 1
            if longtail_idx < len(active_kw_obj["longtails"]):
                target_keyword = active_kw_obj["longtails"][longtail_idx]
                if pillar_kw.lower() not in target_keyword.lower():
                    # Preserve the existing progress but inject the pillar keyword
                    target_keyword = f"{pillar_kw} - {target_keyword}"
            else:
                target_keyword = f"{pillar_kw} phần {current_published}"
                
            print(f"\n[*] Đang xử lý bài CLUSTER ({current_published+1}/10) cho từ khóa: '{target_keyword}'")
            
        pillar_url = active_kw_obj.get("pillar_url", "")
        
        # Generation
        comp_data = research_competitors(target_keyword)
        sale_info = auto_discount_product(products) if products else None
        
        html_content = auto_tool.generate_sales_article(target_keyword, pillar_kw, is_pillar, pillar_url, comp_data, sale_info)
        
        if not html_content:
            print("  [-] Lỗi tạo bài (LLM Timeout/Lỗi). Tạm dừng hệ thống.")
            break
            
        # Extract title from H1 generated by LLM
        soup = BeautifulSoup(html_content, 'html.parser')
        title = target_keyword.capitalize()
        h1 = soup.find('h1')
        if h1:
            title = h1.get_text().strip()
            h1.decompose()
        clean_content = str(soup).strip()
        
        # Image Upload
        kw_featured = auto_tool.get_english_prompt()
        featured_img_url = auto_tool.get_pexels_image_url(kw_featured, 1200, 630, orientation="landscape")
        featured_media_id = auto_tool.upload_image_to_wp(featured_img_url, alt_text=title)
        
        # Post
        post_url = auto_tool.post_to_wordpress(title, clean_content, featured_media_id=featured_media_id)
        
        if post_url:
            print(f"  [+] Đăng bài thành công! URL: {post_url}")
            
            # Update keyword state
            active_kw_obj["published_count"] += 1
            if is_pillar and isinstance(post_url, str):
                active_kw_obj["pillar_url"] = post_url
                
            rank = auto_tool.track_seo_ranking(target_keyword)
            if "history" not in active_kw_obj:
                active_kw_obj["history"] = []
            active_kw_obj["history"].append(rank)
            
            # Update articles history
            db["articles"].append({
                "title": title,
                "keyword": target_keyword,
                "status": "Published",
                "url": post_url if isinstance(post_url, str) else "",
                "date": datetime.now().strftime("%Y-%m-%d")
            })
            
            # Save Database
            with open(db_path, "w", encoding="utf-8") as f:
                json.dump(db, f, ensure_ascii=False, indent=2)
                
            if active_kw_obj["published_count"] < 10:
                print("  [zZz] Tạm nghỉ 10 giây trước khi chạy bài tiếp theo để tránh Limit...")
                time.sleep(10)
        else:
            print("  [-] Lỗi đăng bài lên WordPress. Tạm dừng tiến trình.")
            break
            
    print("\n✅ HOÀN TẤT TIẾN TRÌNH ĐĂNG BÀI CHO TỪ KHÓA:", pillar_kw)

if __name__ == "__main__":
    main()
